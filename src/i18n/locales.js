export const TRANSLATED_LOCALES = SUPPORTED_LOCALES.filter((l) => l.hasTranslations)
export const DEFAULT_LOCALE = 'en'
export const FALLBACK_LOCALE = 'en'
export const LOCALE_STORAGE_KEY = 'eventyay_locale'

export const LOCALE_ALIASES = {
  zh: 'zh_Hans',
  'zh-cn': 'zh_Hans',
  'zh-hans': 'zh_Hans',
  'zh-tw': 'zh_Hant',
  'zh-hk': 'zh_Hant',
  'zh-hant': 'zh_Hant',
  pt: 'pt_BR',
  'pt-br': 'pt_BR',
  'pt-pt': 'pt_PT'
}

export function normalizeLocale(code) {
  if (!code) return DEFAULT_LOCALE
  const clean = String(code).trim()
  if (SUPPORTED_LOCALES.some((l) => l.code === clean)) {
    return clean
  }
  const lower = clean.toLowerCase()
  if (LOCALE_ALIASES[lower]) {
    return LOCALE_ALIASES[lower]
  }
  const langOnly = lower.split(/[-_]/)[0]
  if (LOCALE_ALIASES[langOnly]) {
    return LOCALE_ALIASES[langOnly]
  }
  const match = SUPPORTED_LOCALES.find(
    (l) => l.code.toLowerCase() === lower || l.code.toLowerCase() === langOnly
  )
  return match?.code || DEFAULT_LOCALE
}

export function getLocaleDirection(localeCode) {
  const norm = normalizeLocale(localeCode)
  const locale = SUPPORTED_LOCALES.find((l) => l.code === norm)
  return locale?.dir || 'ltr'
}

export function isSupportedLocale(localeCode) {
  if (!localeCode) return false
  const clean = String(localeCode).trim()
  return (
    SUPPORTED_LOCALES.some((l) => l.code === clean) ||
    Boolean(LOCALE_ALIASES[clean.toLowerCase()])
  )
}

export function isRtlLocale(localeCode) {
  return getLocaleDirection(localeCode) === 'rtl'
}

export function getLocaleMetadata(localeCode) {
  const norm = normalizeLocale(localeCode)
  return SUPPORTED_LOCALES.find((l) => l.code === norm) || null
}
